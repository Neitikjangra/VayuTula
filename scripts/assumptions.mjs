// Generates the README assumptions table and docs/CHECKPOINT_B.md from src/config/*.json.
// Usage: node scripts/assumptions.mjs   (rewrites the README block between the markers)
import { readFileSync, writeFileSync } from 'node:fs';

const START = '<!-- assumptions:start -->';
const END = '<!-- assumptions:end -->';
const read = (file) => JSON.parse(readFileSync(`src/config/${file}`, 'utf8'));
const isValue = (node) => node && typeof node === 'object' && 'value' in node && 'unit' in node;

function flatten(node, prefix, file, out) {
  if (isValue(node)) out.push({ file, key: prefix, ...node });
  else if (node && typeof node === 'object') {
    for (const [k, child] of Object.entries(node)) flatten(child, `${prefix}.${k}`, file, out);
  }
  return out;
}

function entries() {
  const out = [];
  flatten(read('factors.json'), 'factors', 'factors.json', out);
  flatten(read('tariffs.json'), 'tariffs', 'tariffs.json', out);
  flatten(read('ranking.json'), 'ranking', 'ranking.json', out);
  flatten(read('health-library.json').values, 'health', 'health-library.json', out);
  for (const p of read('purifiers.json').models) {
    const { id, brand, model, ...values } = p;
    flatten(values, `purifiers.${id}`, `purifiers.json (${brand} ${model})`, out);
  }
  for (const a of read('actions.json').actions) {
    out.push({ file: 'actions.json', key: `actions.${a.id}.oneOffRupees`, ...a.oneOffRupees });
  }
  return out;
}

/** Where a person should look to verify a value. Suggestions only, never written as a source. */
const SUGGESTIONS = [
  [
    /^factors\.(airExchange|penetration|deposition)/,
    'Peer-reviewed indoor/outdoor PM2.5 studies (infiltration, penetration, deposition), ideally Indian homes',
  ],
  [
    /^factors\.emission\.cooking/,
    'Peer-reviewed cooking PM2.5 emission-rate studies (gas, induction, solid fuel)',
  ],
  [/^factors\.emission\.incense/, 'Peer-reviewed incense-burning PM2.5 emission studies'],
  [/^factors\.emission\.coil/, 'Peer-reviewed mosquito-coil PM2.5 emission studies'],
  [
    /^factors\.emission\.cigarette/,
    'Peer-reviewed or regulator data on second-hand smoke PM2.5 per cigarette',
  ],
  [
    /^factors\.(behaviour|schedules)/,
    'Modelling assumption: confirm with a study or mark as a design choice',
  ],
  [/^factors\.fuelUse/, 'Appliance and LPG consumption studies; Indian household cooking surveys'],
  [/^factors\.co2\.grid/, 'Central Electricity Authority (CEA) CO2 Baseline Database'],
  [/^factors\.co2/, 'IPCC emission factors for LPG, natural gas and biomass'],
  [/^factors\.pm\.grid/, 'Peer-reviewed power-plant PM2.5 emission intensity for the Indian grid'],
  [/^factors\.transport/, 'ARAI / ICCT India vehicle emission factors; DMRC for metro'],
  [/^factors\.devices/, 'Manufacturer specification for liquid vaporisers'],
  [/^tariffs\.electricity/, 'DERC tariff order / Delhi discom (BSES, Tata Power-DDL) schedule'],
  [/^tariffs\.lpg/, 'Indian Oil (IOCL) LPG price list for Delhi'],
  [/^tariffs\.png/, 'Indraprastha Gas (IGL) PNG domestic tariff'],
  [/^tariffs\.(petrol|carKm|twoWheelerKm)/, 'IOCL petrol price for Delhi; ARAI-certified mileage'],
  [/^tariffs\.(bus|metro)/, 'DTC and DMRC fare tables'],
  [/^tariffs\./, 'Retail price survey (manufacturer or major retailer listings)'],
  [/^ranking\./, 'Design choice agreed in R2 (PRD 4.4); mark as such once confirmed'],
  [/^health\./, 'WHO global air quality guidelines (2021)'],
  [/^purifiers\.(generic|unknown|diy)/, 'Design default: confirm against typical market models'],
  [/^purifiers\..*\.cadr/, 'Manufacturer specification sheet (prefer AHAM-verified CADR)'],
  [/^purifiers\./, 'Manufacturer page or authorised retailer listing'],
  [/^actions\./, 'Retail price survey for the item the action asks to buy'],
];
const suggestFor = (key) => SUGGESTIONS.find(([re]) => re.test(key))?.[1] ?? 'To be identified';

const show = (v) => (Array.isArray(v) ? v.join(', ') : String(v));
const status = (e) => (e.verifiedOn ? `verified ${e.verifiedOn}` : 'provisional');

function readmeTable(rows) {
  const head = '| Key | Value | Unit | Source | Status |\n| --- | --- | --- | --- | --- |';
  const body = rows.map(
    (e) => `| \`${e.key}\` | ${show(e.value)} | ${e.unit} | ${e.source} | ${status(e)} |`,
  );
  return [head, ...body].join('\n');
}

function checkpointDoc(rows) {
  const open = rows.filter((e) => !e.verifiedOn);
  const lines = open.map(
    (e) => `| ${e.file} | \`${e.key}\` | ${show(e.value)} ${e.unit} | ${suggestFor(e.key)} |`,
  );
  return [
    '# Checkpoint B: values to verify',
    '',
    `Generated by \`node scripts/assumptions.mjs\`. ${open.length} of ${rows.length} values are unverified (\`verifiedOn: null\`).`,
    'The last column is a suggestion of where to look, not a citation. When you verify a value, send the source and date; it will be written into the config file.',
    '',
    '| File | Key | Current default | Suggested primary source to check |',
    '| --- | --- | --- | --- |',
    ...lines,
    '',
  ].join('\n');
}

const rows = entries();
const readme = readFileSync('README.md', 'utf8');
const [before, rest] = readme.split(START);
if (rest === undefined) throw new Error('README is missing the assumptions markers');
const after = rest.split(END)[1] ?? '';
writeFileSync('README.md', `${before}${START}\n${readmeTable(rows)}\n${END}${after}`);
writeFileSync('docs/CHECKPOINT_B.md', checkpointDoc(rows));
console.log(`${rows.length} values; ${rows.filter((e) => !e.verifiedOn).length} provisional.`);
